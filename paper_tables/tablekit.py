r"""Shared pieces for the paper's table generators (Tables I-III): the IEEEtran table environment, a
standalone preview page, and a matplotlib preview PNG (no LaTeX installed here; the .tex is the
deliverable, the PNG approximates IEEEtran: Times, 8 pt, column 3.5 in, page 7.16 in).

A body is a list of rows. A row is either ("section", latex_text) for an italic block heading,
or a list of LaTeX cell strings; a first cell starting with r"\quad " is indented.
"""
import json
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIT = json.loads((ROOT / "paper_tables" / "literature_values.json").read_text(encoding="utf-8"))
ROMAN = {1: "I", 2: "II", 3: "III", 4: "IV", 5: "V", 6: "VI"}
MACROS = r"""\providecommand{\nnaxi}{NN\_axi}
\providecommand{\nnlive}{NN\_live}"""


def latex_table(*, number, generator, label, colspec, header, body, notes, title, wide=False, tabcolsep=4):
    env = "table*" if wide else "table"
    width = r"\textwidth" if wide else r"\columnwidth"
    ncol = len(header[0])
    lines = []
    for row in body:
        if isinstance(row, tuple) and row[0] == "section":
            lines.append(rf"\multicolumn{{{ncol}}}{{@{{}}l}}{{\textit{{{row[1]}}}}} \\")
        else:
            assert len(row) == ncol, row
            lines.append(" & ".join(row) + r" \\")
    head = "\n".join(" & ".join(h) + r" \\" for h in header)
    notes_tex = "\n".join((rf"\textsuperscript{{{k}}}" if k else "") + v + r"\\" for k, v in notes)
    return rf"""% Table {ROMAN[number]} -- generated by {generator}; do not edit by hand.
% Full provenance notes: table{number}_details.md.
{MACROS}
\begin{{{env}}}[!t]
\caption{{{title}}}
\label{{{label}}}
\centering
\footnotesize
\setlength{{\tabcolsep}}{{{tabcolsep}pt}}
\begin{{tabular}}{{{colspec}}}
\hline
{head}
\hline
{chr(10).join(lines)}
\hline
\end{{tabular}}
\par\vspace{{3pt}}
\parbox{{{width}}}{{\scriptsize
{notes_tex}}}
\end{{{env}}}
"""


def standalone(number, tex_name):
    return rf"""\documentclass[journal]{{IEEEtran}}
% Preview page for Table {ROMAN[number]}. Compile with pdflatex (e.g. on Overleaf).
\usepackage{{amsmath}}
\setcounter{{table}}{{{number - 1}}}
\begin{{document}}
\input{{{tex_name}}}
\end{{document}}
"""


CITE_NUM = {  # preview only: the paper's reference numbers, in order of first citation, so cited cells have their printed width
    "diguglielmo2025": 16, "stefanazzi2022": 17, "farooq2026luna": 35, "dillon2026": 41, "guo2025klinq": 36,
    "vora2026": 20, "lienhard2022": 12, "reuer2023": 19, "le2026": 42, "gaytan2026": 40, "yang2026": 54,
    "liu2025": 52, "hashim2025": 50, "yang2022": 45, "gebauer2020": 46}


def plain(t):
    """LaTeX cell -> matplotlib text (mathtext kept between $...$)."""
    t = re.sub(r"\\textsuperscript\{([^}]*)\}", r"$^{\\rm \1}$", t)
    t = re.sub(r"\\cite\{([^}]*)\}", lambda m: f"[{CITE_NUM.get(m.group(1), m.group(1))}]", t)
    t = re.sub(r"\\textit\{([^}]*)\}", r"\1", t)
    t = re.sub(r"\\textbf\{((?:[^{}]|\{[^{}]*\})*)\}", r"\1", t)
    t = re.sub(r"\\mbox\{([^}]*)\}", r"\1", t)
    for a, b in ((r"\nnaxi{}", "NN_axi"), (r"\nnlive{}", "NN_live"), (r"\quad ", ""), (r"\ ", " "), ("---", "—"), ("--", "–"),
                 (r"\tfrac{1}{2}", r"\frac{1}{2}"), (r"\,", " "), (r"\%", "%"), ("{,}", ","), (r"\times", "×"),
                 (r"\pm", "±"), (r"\to", "→"), (r"\leq", "≤"), (r"\approx", "≈"), (r"\sim", "~"), (r"\&", "&"),
                 ("{}", "")):
        t = t.replace(a, b)
    # unicode symbols are not valid inside mathtext; move them out of $...$ pieces made only of them
    t = re.sub(r"\$([±→≤≈×~])\$", r"\1", t)
    t = re.sub(r"\$(\s*)\$", r"\1", t)
    return t


def write_details(path, number, details, legend=""):
    """The long-form footnotes, kept in the repository rather than in the paper's table."""
    def md(t):
        return re.sub(r"\$\^\{\\rm ([^}]*)\}\$", r"[\1]", plain(t)).replace(r"\geq", ">=").replace(r"\mu", "u").replace(r"\frac{1}{2}", "1/2").replace("$", "")

    out = [f"# Table {ROMAN[number]}: full notes", "", "Generated by the table's script; do not edit by hand. The table in the paper "
           "carries short notes; this file keeps the detail behind them.", ""]
    if legend:
        out += [legend, ""]
    out += [(f"- **{k}** " if k else "- ") + md(v) for k, v in details]
    Path(path).write_text("\n".join(out) + "\n", encoding="utf-8")


def preview(path, *, number, header, body, notes, aligns, wide=False, wrap=None, lh=0.155, colsep_pt=4):
    """Columns are laid out from measured text widths (natural-width tabular, centred, like LaTeX);
    prints a warning when the table is wider than the column or page."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "serif", "font.serif": ["Times New Roman", "DejaVu Serif"],
                         "mathtext.fontset": "stix", "font.size": 8})
    W = 7.16 if wide else 3.5
    wrap = wrap or (190 if wide else 92)
    note_lines = []
    for k, v in notes:
        for i, w in enumerate(textwrap.wrap(plain(v), wrap)):
            note_lines.append(((k if i == 0 else ""), w))
    NH = 0.105
    H = 0.28 + lh * (len(body) + len(header) + 2) + NH * len(note_lines) + 0.15
    fig = plt.figure(figsize=(W, H))
    ax = fig.add_axes([0, 0, 1, 1]); ax.set_xlim(0, W); ax.set_ylim(H, 0); ax.axis("off")
    rend = fig.canvas.get_renderer()

    def width(s):
        t = ax.text(0, 0, s); w = t.get_window_extent(rend).width / fig.dpi; t.remove()
        return w

    ncol = len(aligns); IND = 0.1
    widths = [0.0] * ncol
    for row in header + [r for r in body if not isinstance(r, tuple)]:
        for i, c in enumerate(row):
            widths[i] = max(widths[i], width(plain(c)) + (IND if c.startswith(r"\quad ") else 0))
    sep = 2 * colsep_pt / 72
    total = sum(widths) + sep * (ncol - 1)
    x0 = max(0.02, (W - total) / 2)
    if total > W - 0.04:
        print(f"WARNING: Table {ROMAN[number]} preview is {total:.2f} in wide, page/column is {W - 0.04:.2f} in")
    starts = [x0 + sum(widths[:i]) + sep * i for i in range(ncol)]
    xs = [s + {"left": 0, "center": w / 2, "right": w}[a] for s, w, a in zip(starts, widths, aligns)]
    xl, xr = x0, min(W - 0.02, x0 + total)
    # TQE: the table graphic holds the body only; "TABLE N" and the title go above it as text in the manuscript
    y = 0.06

    def rule(yy):
        ax.plot([xl, xr], [yy, yy], color="k", lw=0.5)

    def cells(row, yy):
        for i, c in enumerate(row):
            ind = IND if (i == 0 and c.startswith(r"\quad ")) else 0
            ax.text(xs[i] + ind, yy, plain(c), ha=aligns[i], va="center")

    rule(y); y += lh * 0.75
    for h in header:
        cells(h, y); y += lh
    rule(y - lh * 0.25); y += lh * 0.55
    for row in body:
        if isinstance(row, tuple):
            ax.text(starts[0], y, plain(row[1]), style="italic", va="center")
        else:
            cells(row, y)
        y += lh
    y -= lh * 0.35; rule(y); y += 0.1
    for k, line in note_lines:
        ax.text(0.02, y, (f"$^{{\\rm {k}}}$" if k else "") + line, va="center", fontsize=5.6); y += NH
    fig.savefig(path, dpi=600)  # TQE: line art, tables included, >= 600 dpi
    plt.close(fig)
