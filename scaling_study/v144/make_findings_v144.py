"""Writes scaling_study/v144/FINDINGS_v144.md: the multi-classifier scaling findings restated on v1.44.

Inputs (read only):
  scaling_study/resource_scaling_v144.json      resources per unit and N_max (from campaign_v144/final/analysis/scaling_v144.py)
  scaling_study/runs/SUMMARY.txt                 OOC timing per unit count (unit RTL = NN_live 1.5, unchanged in v1.43/v1.44)
  scaling_study/runs/<run>/timing_routed.rpt     worst path per OOC run
  firmware_v1.44/reports/v144_decision_path_slack.tsv   integrated v1.44 decision-path slacks (this folder)
Does not touch scaling_study/FINDINGS.md.

"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
REP = ROOT / "firmware_v1.44" / "reports"
SS = ROOT / "scaling_study"
J = json.loads((SS / "resource_scaling_v144.json").read_text())

runs = {}
for line in (SS / "runs" / "SUMMARY.txt").read_text().splitlines():
    m = re.search(r"SUMMARY (?:(ZL|T) )?N=(\d+) mode=(\w+) WNS=(-?[\d.]+) .*?failing_unit=(\d+) .*?failing_harness=(\d+)", line)
    if not m:
        continue
    var, n, mode, wns, fu, fh = m.groups()
    var = var or "v1.41"
    d = f"N{n}_{mode}" + {"ZL": "_zl", "T": "_t"}.get(var, "")
    rpt = SS / "runs" / d / "timing_routed.rpt"
    line_no, dst = "", ""
    if rpt.exists():
        lines = rpt.read_text(errors="ignore").splitlines()
        i = next(k for k, s in enumerate(lines) if s.startswith("Max Delay Paths"))
        for k in range(i, i + 12):
            if "Destination:" in lines[k]:
                dst = lines[k].split()[-1]; line_no = k + 1
                break
    runs[(var, int(n), mode)] = dict(wns=float(wns), fu=int(fu), fh=int(fh), dst=dst, ref=f"runs/{d}/timing_routed.rpt:{line_no}")

def where(p):
    if "/u_cdc" in p:
        return "CDC hold register (" + p.split("/")[1] + ")"
    if "lr_1_reg" in p:
        return "NN_live lr_1_reg (saturated logit)"
    if "res_r_reg" in p:
        return "res_o register (ZL variant)"
    if "WROM_U" in p:
        return "NN_live weight ROM"
    if "frp_pipeline_valid" in p:
        return "NN_live valid pipeline (reset)"
    if "u_nn" in p:
        return "NN_live accumulator " + p.split("/")[-2]
    return p

dp = {}
tsv = REP / "v144_decision_path_slack.tsv"
if tsv.exists():
    for r in tsv.read_text().splitlines()[1:]:
        f = r.split("\t")
        if len(f) >= 3 and f[1] == "setup" and f[2] not in ("NO_PATH", ""):
            dp[f[0]] = float(f[2])

nm = J["n_max"]
L = []
w = L.append
w("# Multi-classifier scaling on v1.44 (regenerated)")
w("")
w("Generated by `scaling_study/v144/make_findings_v144.py`; do not edit by hand. "
  "`scaling_study/FINDINGS.md` (the v1.41 analysis) is left as it is.")
w("")
w("Sources: `scaling_study/resource_scaling_v144.json` (v1.44 routed reports, via "
  "`campaign_v144/final/analysis/scaling_v144.py`); `scaling_study/runs/SUMMARY.txt` and each run's "
  "`timing_routed.rpt` (out-of-context runs); integrated v1.44 slacks from "
  "`firmware_v1.44/reports/v144_decision_path_slack.tsv` (routed v1.44 checkpoint, this folder).")
w("")
w("v1.44 is the v1.43 design placed and routed again; the classifier unit's RTL (NN_live 1.5, boxcar, window gate, "
  "CDC, dac_gate) is the one the OOC study used, so the OOC timing applies to v1.44 unchanged.")
w("")
w("## Resources per unit (v1.44 routed)")
w("")
pu = J["per_unit"]
w("| part | LUT | FF | BRAM tiles | DSP |")
w("|---|---|---|---|---|")
for k, lab in (("classifier", "classifier (NN_live + boxcar + window gate + trig_sync + 2 CDC)"), ("dac_gate", "dac_gate"),
               ("record_memory", "record memory (verification only)")):
    c = pu[k]; w(f"| {lab} | {c['lut']:,} | {c['ff']:,} | {c['bram']:g} | {c['dsp']} |")
for k, lab in (("fir_free", "per-tone front end: DDS/mixer only (FIR-free)"), ("stock", "per-tone front end: stock QICK readout with FIR")):
    c = pu["front_end"][k]; w(f"| {lab} | {c['lut']:,} | {c['ff']:,} | {c['bram']:g} | {c['dsp']} |")
w("")
w("## Largest unit count that fits (resources only)")
w("")
w("| baseline | front end | record memory | N_max | binding |")
w("|---|---|---|---|---|")
for k, v in nm.items():
    base, fe, rec = [s.strip() for s in k.split("|")]
    w(f"| {base} | {fe.replace('front end ', '')} | {rec.replace('record ', '')} | **{v['n_max']}** | {', '.join(v['binding'])} |")
lo = nm["as built | front end stock | record yes"]
hi = nm["minus NN_axi (and time tagger if present) | front end fir_free | record no"]
w("")
w(f"With a per-tone front end the range is **{lo['n_max']}–{hi['n_max']} units**:")
w("")
w(f"* **{lo['n_max']}**: the design as built (NN_axi kept), every tone with QICK's stock readout including its FIR, "
  f"record memory kept; bound by {', '.join(lo['binding']).upper()}.")
w(f"* **{hi['n_max']}**: NN_axi removed, a DDS/mixer-only (FIR-free) front end per tone, no record memory; "
  f"bound by {', '.join(hi['binding']).upper()}.")
w("")
w("Without a per-tone front end (all units on one stream) the unit alone fits 51–100 times; QICK's front end "
  "(16 BRAM tiles of DDS tables and 35–157 DSP per tone), not our logic, sets the resource limit.")
w("")
w("## Timing per unit count (OOC, setup at 552.96 MHz, clk_adc0_x2 1.809 ns)")
w("")
w("`pb` = all units in v1.41's pb_live (CLOCKREGION_X4Y3:X5Y4, at most ~11 units); `free` = whole device.")
w("")
w("| N | placement | RTL | WNS (ns) | failing endpoints (unit / harness) | worst path ends at | report |")
w("|---|---|---|---|---|---|---|")
for key in sorted(runs, key=lambda k: ({"v1.41": 0, "ZL": 1, "T": 2}[k[0]], k[1])):
    r = runs[key]
    w(f"| {key[1]} | {key[2]} | {key[0]} | {r['wns']:+.3f} | {r['fu']:,} / {r['fh']:,} | {where(r['dst'])} | `{r['ref']}` |")
w("")
w("The deployed RTL closes at N = 1, 2 and 4 (pb) and 16 (free), and fails at N = 8 (pb, −0.011 ns) and N = 32 (free, "
  "−0.183 ns). Only N = 4 and N = 16 are near zero (+0.002 ns); N = 1 and N = 2 have +0.171 and +0.103 ns.")
w("")
w("**Limiting path:** NN_live's fused tail (the last ACC_L iteration computes the rectified units, the signed sums and "
  "the saturating select in one cycle) driving `res_o` combinationally into the two CDC hold registers and into "
  "`lr_1_reg`. It is the worst path at N = 2, 4, 8 and 16. At N = 1 the worst path is NN_live's loop-init register into "
  "an accumulator; at N = 32 an accumulator DSP path, with failures spread over all units (607 of 1,103 in dac_gate's "
  "DAC-domain path; `scaling_study/FINDINGS.md`).")
w("")
w("**Remedy (OOC only, not deployed, not re-verified):** one extra tail register. Variant T (NN_live re-synthesized with "
  "one more ACC_L stage, register-free window gate, same 10-cycle end-to-end latency) closes N = 8 at +0.029 ns and "
  "N = 4 at +0.063 ns; variant ZL (gate register moved onto `res_o`) closes N = 8 at +0.006 ns.")
w("")
w("## Integration penalty")
w("")
n1 = runs[("v1.41", 1, "pb")]["wns"]
w(f"OOC N = 1: {n1:+.3f} ns. The same unit's decision path inside the full design:")
w("")
w("| build | worst path through NN_live | NN_live → CDC hold registers | penalty vs OOC N = 1 |")
w("|---|---|---|---|")
w("| v1.41 (`scaling_study/FINDINGS.md`) | −0.141 ns | −0.042 ns (live_res_cdc_0) | 0.171 + 0.141 = 0.31 ns (NN_live), 0.171 + 0.042 = 0.21 ns (CDC) |")
if dp:
    a, b0, b1 = dp.get("nn_live_through"), dp.get("nnlive_to_cdc0"), dp.get("nnlive_to_cdc1")
    w(f"| v1.44 (this folder) | {a:+.3f} ns | {b0:+.3f} ns (cdc_0), {b1:+.3f} ns (cdc_1) | "
      f"{n1 - a:.2f} ns (NN_live), {n1 - min(b0, b1):.2f} ns (CDC) |")
w("")
w("OOC N = 1's +0.171 ns is the unit's worst path, so every path of the unit, the tail included, had at least that; "
  "the penalties are lower bounds. In v1.44 the worst path through NN_live is no longer the tail but the weight-ROM "
  "lookup (`ap_start_reg` → `WROM_U/q0_reg[8]`, +0.001 ns); the tail into the CDC hold registers is at +0.021 ns. "
  "The full design costs ~0.2 ns of the unit's OOC margin (at least 0.15–0.17 ns in v1.44, 0.21–0.31 ns in v1.41). "
  "v1.44 closes where v1.41 did not, by 1–31 ps on these paths. With N = 2 already at +0.103 ns out of context, an integrated build with two or more "
  "units would be expected to fail on the tail path unless it carries the extra tail register, whose +0.03–0.06 ns "
  "out-of-context gain is itself smaller than the integration penalty. **Timing on the tail path, not resources, is "
  "the first limit.** No integrated multi-unit build was made.")
(HERE / "FINDINGS_v144.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"wrote {HERE / 'FINDINGS_v144.md'} ({len(L)} lines)")
